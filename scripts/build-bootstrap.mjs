// Regenerates the three pasteable bootstrap SQL files from the source
// migrations + catalog seeds. Run: node scripts/build-bootstrap.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const GROUPS = [
  [
    'supabase/migrations/0001_foundation.sql',
    'supabase/migrations/0002_clinical.sql',
    'supabase/migrations/0003_functions.sql',
    'supabase/migrations/0004_booking.sql',
    'supabase/migrations/0005_rls.sql',
    'supabase/migrations/0006_auth_helpers.sql',
  ],
  [
    'supabase/migrations/0007_rls_policies.sql',
    'supabase/migrations/0008_doctor_discovery.sql',
    'supabase/migrations/0009_admin_control.sql',
    'supabase/migrations/0010_payments.sql',
    'supabase/migrations/0011_wow_features.sql',
    'supabase/migrations/0012_realtime.sql',
    'supabase/migrations/0013_profile_provisioning.sql',
  ],
  ['supabase/seed_01_catalog.sql', 'supabase/seed_02_doctors.sql', 'supabase/seed_03_postings.sql'],
];

GROUPS.forEach((group, i) => {
  const n = i + 1;
  let out = `-- MediNova bootstrap part ${n} of 3.\n`;
  out += '-- Run parts 1, 2, 3 IN ORDER in the Supabase SQL Editor. Run each part exactly once.\n';
  out += '-- Generated by scripts/build-bootstrap.mjs - do not edit by hand.\n\n';
  for (const f of group) {
    out += `-- ======== ${f.split('/').pop()} ========\n`;
    out += `${readFileSync(f, 'utf8').replace(/\s+$/, '')}\n\n`;
  }
  writeFileSync(`supabase/bootstrap-${n}.sql`, out, 'utf8');
  console.log(`bootstrap-${n}.sql: ${out.length} bytes, ${group.length} files`);
});
